function buildSeeds(level: Level, entries: Entry[]): Seed[] {
  const seen = new Set<string>();
  const seeds: Seed[] = [];
  for (const [hangul, zh, pos] of entries) {
    const romaja = hangulToRomaja(hangul);
    const slug = slugify(romaja);
    if (!slug) continue;
    let id = `ko-vocab-${level.toLowerCase()}-${slug}`;
    let suffix = 2;
    while (seen.has(id)) {
      id = `ko-vocab-${level.toLowerCase()}-${slug}-${suffix++}`;
    }
    seen.add(id);
    seeds.push({
      id,
      type: "vocab",
      level,
      ja: hangul,
      reading: romaja,
      zh,
      pos,
    });
  }
  return seeds;
}

function writeYaml(level: Level, entries: Entry[], outFile: string): number {
  const seeds = buildSeeds(level, entries);
  const doc = { language: "ko", concepts: seeds };
  if (!existsSync(SEEDS_DIR)) mkdirSync(SEEDS_DIR, { recursive: true });
  writeFileSync(outFile, YAML.stringify(doc), "utf-8");
  return seeds.length;
}

