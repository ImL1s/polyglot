// ---------------------------------------------------------------------------
// Hangul → Revised Romanization (RR) for slug generation.
//
// Hangul syllables are composed in Unicode by:
//   code = 0xAC00 + (initial * 21 + medial) * 28 + final
// We decompose the syllable, map each jamo to its RR letter, then concatenate.
// We do NOT implement the full RR rules (assimilation, batchim sandhi) — for
// slugs we want a stable letter-for-letter mapping, not phonetic accuracy.
// ---------------------------------------------------------------------------

const INITIALS = [
  "g", "kk", "n", "d", "tt", "r", "m", "b", "pp", "s",
  "ss", "", "j", "jj", "ch", "k", "t", "p", "h",
];
const MEDIALS = [
  "a", "ae", "ya", "yae", "eo", "e", "yeo", "ye", "o", "wa",
  "wae", "oe", "yo", "u", "wo", "we", "wi", "yu", "eu", "ui", "i",
];
const FINALS = [
  "", "g", "kk", "gs", "n", "nj", "nh", "d", "l", "lg",
  "lm", "lb", "ls", "lt", "lp", "lh", "m", "b", "bs", "s",
  "ss", "ng", "j", "ch", "k", "t", "p", "h",
];

const HANGUL_BASE = 0xAC00;
const HANGUL_END = 0xD7A3;

export function hangulToRomaja(s: string): string {
  let out = "";
  for (const ch of s) {
    const code = ch.codePointAt(0)!;
    if (code < HANGUL_BASE || code > HANGUL_END) {
      // pass through ASCII / spaces / hyphens
      out += ch;
      continue;
    }
    const offset = code - HANGUL_BASE;
    const initial = Math.floor(offset / (21 * 28));
    const medial = Math.floor((offset % (21 * 28)) / 28);
    const final_ = offset % 28;
    out += INITIALS[initial] + MEDIALS[medial] + FINALS[final_];
  }
  return out;
}

export function slugify(romaja: string): string {
  return romaja
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

